package isel.dei.pdm.demos.gamevault.adapters.room

import androidx.room.ColumnInfo
import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey
import isel.dei.pdm.demos.gamevault.domain.collection.NewPlatform
import isel.dei.pdm.demos.gamevault.domain.collection.Platform

/**
 * The database representation of a platform in the user's collection.
 *
 * The triple <abbreviation, name, version> is unique, ignoring case. Because SQLite considers NULLs
 * to be distinct in unique indexes, a platform without version is stored with an empty [version],
 * instead of NULL. Otherwise, the same platform without version could be stored more than once.
 *
 * @property id The unique identifier of the platform, generated by the database.
 * @property abbreviation The platform's abbreviation (e.g. PS5, XBOX).
 * @property name The platform's full name (e.g. PlayStation 5).
 * @property version The platform's version (e.g. Pro), or empty if it has none.
 * @property logoUri The URI of the platform's logo, if available.
 * @property ownedSince The year the platform was acquired, if available.
 */
@Entity(
    tableName = "platforms",
    indices = [Index(value = ["abbreviation", "name", "version"], unique = true)]
)
data class PlatformEntity(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0,
    @ColumnInfo(collate = ColumnInfo.NOCASE)
    val abbreviation: String,
    @ColumnInfo(collate = ColumnInfo.NOCASE)
    val name: String,
    @ColumnInfo(collate = ColumnInfo.NOCASE)
    val version: String,
    @ColumnInfo(name = "logo_uri")
    val logoUri: String?,
    @ColumnInfo(name = "owned_since")
    val ownedSince: Int?
)

/**
 * Converts this platform to be added to the collection to its database representation.
 */
fun NewPlatform.toEntity(): PlatformEntity = PlatformEntity(
    abbreviation = abbreviation.value,
    name = name.value,
    version = version?.value.orEmpty(),
    logoUri = logoUri?.toString(),
    ownedSince = ownedSince?.value
)

/**
 * Converts this database representation to the corresponding domain platform.
 * @throws IllegalArgumentException if the stored data does not meet the domain requirements.
 */
fun PlatformEntity.toPlatform(): Platform = Platform(
    id = id,
    abbreviation = abbreviation,
    name = name,
    logoUri = logoUri,
    ownedSince = ownedSince,
    version = version.ifEmpty { null }
)
