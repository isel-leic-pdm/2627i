import kotlin.time.Instant

/**
 * The database representation of a game in the user's collection, along with its collection
 * entry's scalar information (play state, time spent, platinum, session).
 *
 * The collection has exactly one entry per game, and removing the entry removes the game, so both
 * are stored in the same row: the one-to-one relation is enforced by the schema itself, and the
 * listings (see [isel.dei.pdm.demos.gamevault.domain.collection.games.CollectionItem]) do not
 * require joins, apart from the platforms' abbreviations. The entry's collections are stored in
 * their own tables (see [GamePlatformEntity] and [CompletedRunEntity]), as are the game's
 * details, which are only loaded when working with a single game (see [GameDetailsEntity]).
 *
 * Dates and instants are stored as SQLite understands them (see [DateTimeConverters]). The time
 * spent is stored as a total of minutes, so that it can be added up in queries. Enumerations are
 * stored by name, as in [PlatformEntity].
 *
 * Domain rules that span several rows are not expressible in the schema, and are enforced by the
 * repository instead: the same game is not added twice (see [NewGame.isSameGameAs]), and at most
 * one session is active at a time.
 *
 * @property id The unique identifier of the game, generated by the database.
 * @property name The game's name. Compared ignoring case, as listings are sorted that way (note
 * that SQLite's NOCASE only folds ASCII letters).
 * @property releaseDate The game's release date, or null if unknown.
 * @property coverUri The URI of the game's cover image, if available.
 * @property thumbnailUri The URI of the game's thumbnail image, if available.
 * @property state The name of the entry's play state (see [PlayStatus.State]).
 * @property timeSpentMinutes The total time spent playing, in minutes.
 * @property hasPlatinum Whether the platinum was obtained. It is stored apart from its date, as
 * the platinum may have been obtained on an unknown date.
 * @property platinumOn The date the platinum was obtained, or null if not obtained, or obtained
 * on an unknown date. Only filled if [hasPlatinum] is true.
 * @property addedAt The instant the game was added to the collection.
 * @property sessionStartTime The instant the active play session started, or null if no session
 * is active.
 */
@Entity(
    tableName = "games",
    indices = [
        // Listings are sorted by name
        Index(value = ["name"]),
        // The candidates to being the same game are looked up by release year
        Index(value = ["release_date"]),
        // The active session is looked up on its own (see observeActiveSession)
        Index(value = ["session_start_time"])
    ]
)
data class GameEntity(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0,
    @ColumnInfo(collate = ColumnInfo.NOCASE)
    val name: String,
    @ColumnInfo(name = "release_date")
    val releaseDate: LocalDate?,
    @ColumnInfo(name = "cover_uri")
    val coverUri: String?,
    @ColumnInfo(name = "thumbnail_uri")
    val thumbnailUri: String?,
    val state: String,
    @ColumnInfo(name = "time_spent_minutes")
    val timeSpentMinutes: Int,
    @ColumnInfo(name = "has_platinum")
    val hasPlatinum: Boolean,
    @ColumnInfo(name = "platinum_on")
    val platinumOn: LocalDate?,
    @ColumnInfo(name = "added_at")
    val addedAt: Instant,
    @ColumnInfo(name = "session_start_time")
    val sessionStartTime: Instant?
)

/**
 * Converts this game to be added to the collection to its database representation, with the
 * given entry information. Its completed runs are stored apart (see [toRunEntities]).
 * @param playStatus The entry's initial play status.
 * @param addedAt The instant the game is added to the collection.
 */
fun NewGame.toEntity(playStatus: PlayStatus, addedAt: Instant): GameEntity = GameEntity(
    name = name.value,
    releaseDate = releaseDate,
    coverUri = coverUri?.toString(),
    thumbnailUri = thumbnailUri?.toString(),
    state = playStatus.state.name,
    timeSpentMinutes = playStatus.timeSpent.toMinutes(),
    hasPlatinum = playStatus.platinum != null,
    platinumOn = playStatus.platinum?.achievedOn,
    addedAt = addedAt,
    sessionStartTime = null
)

/**
 * Converts this entry to the database representation of its game. Its platforms and completed
 * runs are stored apart (see [toPlatformEntities] and [toRunEntities]).
 */
fun CollectionEntry.toEntity(): GameEntity = GameEntity(
    id = game.id,
    name = game.name.value,
    releaseDate = game.releaseDate,
    coverUri = game.coverUri?.toString(),
    thumbnailUri = game.thumbnailUri?.toString(),
    state = playStatus.state.name,
    timeSpentMinutes = playStatus.timeSpent.toMinutes(),
    hasPlatinum = playStatus.platinum != null,
    platinumOn = playStatus.platinum?.achievedOn,
    addedAt = addedAt,
    sessionStartTime = sessionStartTime
)

/**
 * Converts this database representation to the corresponding domain game.
 * @throws IllegalArgumentException if the stored data does not meet the domain requirements.
 */
fun GameEntity.toGame(): Game = Game(
    id = id,
    name = name,
    releaseDate = releaseDate,
    coverUri = coverUri,
    thumbnailUri = thumbnailUri
)

/**
 * Converts this database representation, along with the entry's information stored apart, to the
 * corresponding collection entry.
 * @param platforms The platforms the game is owned on.
 * @param runs The game's completed runs.
 * @throws IllegalArgumentException if the stored data does not meet the domain requirements.
 */
fun GameEntity.toCollectionEntry(
    platforms: List<Platform>,
    runs: List<CompletedRunEntity>
): CollectionEntry = CollectionEntry(
    game = toGame(),
    platforms = platforms.toSet(),
    playStatus = PlayStatus(
        timeSpent = timeSpentMinutes.minutes.toPlayTime(),
        state = PlayStatus.State.valueOf(state),
        completedRuns = runs.map { it.toAccomplishment() },
        platinum = toPlatinum()
    ),
    addedAt = addedAt,
    sessionStartTime = sessionStartTime
)

/**
 * Converts the stored platinum columns to the corresponding accomplishment.
 * @throws IllegalArgumentException if a date is stored without the platinum.
 */
private fun GameEntity.toPlatinum(): Accomplishment? {
    if (!hasPlatinum) {
        require(platinumOn == null) { "Platinum date stored without the platinum" }
        return null
    }
    return Accomplishment(platinumOn)
}

/**
 * The total of minutes of this play time.
 */
private fun PlayTime.toMinutes(): Int = toDuration().inWholeMinutes.toInt()
