package isel.dei.pdm.demos.gamevault.adapters.room

import androidx.room.ColumnInfo
import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.Index
import androidx.room.PrimaryKey
import isel.dei.pdm.demos.gamevault.domain.collection.games.Accomplishment
import isel.dei.pdm.demos.gamevault.domain.collection.games.PlayStatus
import kotlinx.datetime.LocalDate

/**
 * The database representation of a run completed by the user (see [PlayStatus.completedRuns]).
 *
 * Several runs of a game may be completed on the same date, or have no known date, so runs have
 * an identifier of their own, generated by the database, instead of being identified by their
 * game and date. The runs are not ordered: the first finish is the earliest run, the undated
 * ones being the earliest (see [PlayStatus.wasFirstFinishedIn]). Conveniently, SQLite sorts
 * NULLs first in ascending order, but note that aggregate functions (e.g. MIN) ignore them.
 *
 * Removing a game removes its runs (CASCADE).
 *
 * @property id The unique identifier of the run, generated by the database.
 * @property gameId The game's identifier.
 * @property completedOn The date the run was completed (see [DateTimeConverters]), or null if
 * unknown.
 */
@Entity(
    tableName = "completed_runs",
    foreignKeys = [
        ForeignKey(
            entity = GameEntity::class,
            parentColumns = ["id"],
            childColumns = ["game_id"],
            onDelete = ForeignKey.CASCADE
        )
    ],
    indices = [
        // Runs are looked up by game, and by date for the yearly figures of the summary. It also
        // serves the foreign key, which would otherwise require a full scan on each game removal.
        Index(value = ["game_id", "completed_on"])
    ]
)
data class CompletedRunEntity(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0,
    @ColumnInfo(name = "game_id")
    val gameId: Long,
    @ColumnInfo(name = "completed_on")
    val completedOn: LocalDate?
)

/**
 * Converts the completed runs of the given play status to their database representation.
 * @param gameId The identifier of the game the play status belongs to.
 */
fun PlayStatus.toRunEntities(gameId: Long): List<CompletedRunEntity> =
    completedRuns.map { CompletedRunEntity(gameId = gameId, completedOn = it.achievedOn) }

/**
 * Converts this database representation to the corresponding accomplishment.
 */
fun CompletedRunEntity.toAccomplishment(): Accomplishment = Accomplishment(completedOn)
